const DICTS: Record<Lang, Dict> = { en, sr, de, fr, es, it, nl, pt, pl, sv, tr, ru, ar };

const STORE = "spacematch.lang";

function detect(): Lang {
  const q = new URLSearchParams(location.search).get("lang");
  const saved = (() => {
    try {
      return localStorage.getItem(STORE);
    } catch {
      return null;
    }
  })();
  const nav = navigator.language?.slice(0, 2).toLowerCase();
  for (const c of [q, saved, nav]) {
    if (c && DICTS[c as Lang]) return c as Lang;
  }
  // Srpskohrvatski govorni prostor deli isti tekst
  if (nav && ["hr", "bs", "me"].includes(nav)) return "sr";
  return "en";
}

let lang: Lang = detect();

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem(STORE, l);
  } catch {
    /* privatni režim — izbor važi za ovu sesiju */
  }
  applyDir();
}

/** Arapski se čita zdesna nalevo — ceo dokument mora da se okrene. */
export function applyDir() {
  const meta = LANGS.find((l) => l.code === lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = meta?.rtl ? "rtl" : "ltr";
}

/** Ime jezika na engleskom — tako se traži od modela („write in German"). */
export const aiLanguage = () => LANGS.find((l) => l.code === lang)?.ai ?? "English";

export const t = (k: string) => DICTS[lang]?.[k] ?? en[k] ?? k;
